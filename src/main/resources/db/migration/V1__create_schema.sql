CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL,
    birth_date DATE NOT NULL,
    join_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    gender VARCHAR(30),
    emergency_contact VARCHAR(120),
    notes VARCHAR(1000),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description VARCHAR(400) NOT NULL,
    monthly_price DECIMAL(10, 2) NOT NULL,
    duration_months INTEGER NOT NULL,
    features VARCHAR(800) NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    plan_id BIGINT NOT NULL REFERENCES plans(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    monthly_price DECIMAL(10, 2) NOT NULL,
    discount_percent DECIMAL(5, 2) NOT NULL
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL REFERENCES memberships(id),
    reference_date DATE NOT NULL,
    due_date DATE NOT NULL,
    paid_at DATE,
    amount DECIMAL(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    method VARCHAR(30),
    note VARCHAR(500)
);

CREATE TABLE check_ins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    checked_in_at TIMESTAMP NOT NULL
);

CREATE TABLE workout_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    title VARCHAR(100) NOT NULL,
    goal VARCHAR(120) NOT NULL,
    coach VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_plan_id BIGINT NOT NULL REFERENCES workout_plans(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    muscle_group VARCHAR(80) NOT NULL,
    set_count INTEGER NOT NULL,
    repetitions VARCHAR(30) NOT NULL,
    rest_seconds INTEGER NOT NULL,
    notes VARCHAR(400),
    position INTEGER NOT NULL
);

CREATE TABLE physical_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    assessment_date DATE NOT NULL,
    weight DECIMAL(6, 2) NOT NULL,
    height DECIMAL(4, 2) NOT NULL,
    body_fat_percentage DECIMAL(5, 2),
    muscle_mass DECIMAL(6, 2),
    waist DECIMAL(6, 2),
    chest DECIMAL(6, 2),
    arm DECIMAL(6, 2),
    thigh DECIMAL(6, 2),
    notes VARCHAR(600)
);

CREATE INDEX idx_members_status ON members(status);
CREATE INDEX idx_members_name ON members(name);
CREATE INDEX idx_memberships_member ON memberships(member_id);
CREATE INDEX idx_memberships_status ON memberships(status);
CREATE INDEX idx_payments_due_date ON payments(due_date);
CREATE INDEX idx_payments_status ON payments(status);
CREATE INDEX idx_check_ins_date ON check_ins(checked_in_at);
CREATE INDEX idx_workout_plans_member ON workout_plans(member_id);
CREATE INDEX idx_assessments_member_date ON physical_assessments(member_id, assessment_date);
